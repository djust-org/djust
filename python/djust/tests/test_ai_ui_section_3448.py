"""One UI discovery section for the manifest, context files and generated docs."""

import argparse
from pathlib import Path
import tomllib

import pytest

from djust.ai_discovery import manifest
from djust.management.commands import djust_ai_context as context
from djust.schema import get_framework_schema


def test_ui_use_cases_name_catalog_entries():
    from djust.ai_discovery.catalog import get_entry

    for _, names in manifest.UI_USE_CASES:
        for name in names:
            entry = get_entry(name)
            assert entry is not None and entry.name == name


def test_ui_use_cases_cover_the_x1xx_suggestions():
    from djust.checks.ai_discovery import _UI_REPLACEMENTS

    names = {name for _, group in manifest.UI_USE_CASES for name in group}
    assert {name for group in _UI_REPLACEMENTS.values() for name in group} <= names


def test_section_renders_every_use_case_and_component():
    from djust.ai_discovery.catalog import get_entry

    section = manifest.render_ui_building_blocks()
    for use_case, names in manifest.UI_USE_CASES:
        assert use_case in section
        for name in names:
            entry = get_entry(name)
            needle = "`{% " + name + " %}`" if entry.kind == "tag" else "`" + name + "`"
            assert needle in section
    assert section.endswith("\n") and not section.endswith("\n\n")


def test_section_lists_the_discovery_commands():
    from djust.ai_discovery.agents import DISCOVERY_COMMANDS

    section = manifest.render_ui_building_blocks()
    for invocation in ("python manage.py check", "python manage.py djust_check"):
        assert invocation in section
    assert all(command.invocation in section for command in DISCOVERY_COMMANDS)


def test_section_setup_names_resolve():
    from djust.components.apps import DjustComponentsConfig
    from djust.components.templatetags.djust_components import register
    from djust.theming.templatetags.theme_tags import register as themes
    from djust.theming.management.commands.djust_theme import Command

    section = manifest.render_ui_building_blocks()
    assert "app_shell" in register.tags
    assert "theme_head" in themes.tags and "theme_head" in section
    project = Path(__file__).resolve().parents[3] / "pyproject.toml"
    assert "components" in tomllib.loads(project.read_text())["project"]["optional-dependencies"]
    assert DjustComponentsConfig.name == "djust.components" and "djust.components" in section
    parser = argparse.ArgumentParser()
    Command().add_arguments(parser)
    assert parser.parse_args(["list-presets"]).subcommand == "list-presets"


def test_section_is_version_free_and_deterministic():
    from djust import __version__

    section = manifest.render_ui_building_blocks()
    assert section == manifest.render_ui_building_blocks()
    assert __version__ not in section


@pytest.mark.parametrize("fmt", ["claude", "cursor", "copilot"])
def test_ai_context_has_the_section_after_the_intro(fmt):
    text = context._generate_content(get_framework_schema(), {}, fmt)
    assert (
        text.index("This project uses the **djust** framework")
        < text.index(manifest.render_ui_building_blocks())
        < text.index("## Template Directives")
    )


@pytest.mark.parametrize("fmt", ["claude", "cursor", "copilot"])
def test_ai_context_is_otherwise_byte_identical(fmt):
    fw = get_framework_schema()
    project = {
        "views": [
            {
                "class": "RecordsView",
                "template": "records.html",
                "auth": {"login_required": True, "permission_required": ["records.view"]},
                "handlers": [
                    {
                        "name": "search",
                        "params": [{"name": "value", "type": "str"}],
                        "decorators": {"event_handler": True},
                    }
                ],
                "exposed_state": {"query": "str"},
            }
        ],
        "components": [{"class": "RecordCard", "template": "card.html"}],
        "routes": [{"pattern": "records/", "view": "RecordsView", "name": "records"}],
    }
    titles = {"claude": "CLAUDE.md", "cursor": ".cursorrules", "copilot": "Copilot Instructions"}
    sections = [
        "# %s — djust Project Context\n" % titles[fmt],
        "Auto-generated by `python manage.py djust_ai_context --format %s`.\n" % fmt,
        "Regenerate it with the same command after upgrading djust or adding views. The command "
        "refuses to overwrite an existing file unless you pass `--force`, so keep your own rules "
        "in a separate file.\n",
        "This project uses the **djust** framework (v%s) — "
        "a hybrid Python/Rust framework bringing Phoenix LiveView-style "
        "reactive server-side rendering to Django.\n" % fw.get("version", "?"),
        context._section_directives(fw),
        context._section_lifecycle(fw),
        context._section_decorators(fw),
        context._section_conventions(fw),
        context._section_security(),
        context._section_state(),
        context._section_project_views(project),
        context._section_routes(project),
    ]
    text = context._generate_content(fw, project, fmt)
    assert text.replace(manifest.render_ui_building_blocks() + "\n", "", 1) == "\n".join(sections)


