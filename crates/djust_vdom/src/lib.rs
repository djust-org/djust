// ============================================================================
// Compact ID Generation (Base62)
// ============================================================================

// Thread-local counter for generating unique IDs within a parse session.
//
// Thread Safety: This counter is thread-local, meaning each thread has its own
// independent counter. This ensures that concurrent parses in different threads
// don't interfere with each other's ID sequences, which is important for:
//
// 1. Test isolation - parallel tests don't affect each other
// 2. Concurrent request handling - each request gets sequential IDs
// 3. Deterministic output - same input always produces same IDs
//
// Call `reset_id_counter()` before parsing to reset the counter (this is
// done automatically by `parse_html()`).
thread_local! {
    static ID_COUNTER: Cell<u64> = const { Cell::new(0) };
}

/// Base62 character set: 0-9, a-z, A-Z
const BASE62_CHARS: &[u8] = b"0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ";

/// Convert a number to base62 string (compact encoding)
///
/// Examples:
/// - 0 → "0"
/// - 61 → "Z"
/// - 62 → "10"
/// - 3843 → "ZZ"
///
/// 2 chars = 3,844 unique IDs (sufficient for most pages)
/// 3 chars = 238,328 unique IDs (sufficient for any page)
pub fn to_base62(mut n: u64) -> String {
    if n == 0 {
        return "0".to_string();
    }

    let mut result = Vec::new();
    while n > 0 {
        result.push(BASE62_CHARS[(n % 62) as usize]);
        n /= 62;
    }
    result.reverse();
    String::from_utf8(result).unwrap()
}

/// Generate the next unique djust_id
pub fn next_djust_id() -> String {
    ID_COUNTER.with(|counter| {
        let id = counter.get();
        counter.set(id + 1);
        let djust_id = to_base62(id);
        vdom_trace!("next_djust_id() -> {} (counter was {})", djust_id, id);
        djust_id
    })
}

/// Reset the ID counter (call before parsing a new document)
pub fn reset_id_counter() {
    vdom_trace!("reset_id_counter() - resetting to 0");
    ID_COUNTER.with(|counter| counter.set(0));
}

/// Get the current ID counter value (for session persistence)
pub fn get_id_counter() -> u64 {
    let value = ID_COUNTER.with(|counter| counter.get());
    vdom_trace!("get_id_counter() -> {}", value);
    value
}

/// Set the ID counter to a specific value (for session restoration)
pub fn set_id_counter(value: u64) {
    vdom_trace!("set_id_counter({})", value);
    ID_COUNTER.with(|counter| counter.set(value));
}

/// Decode a base62 string back to its u64 value.
///
/// Inverse of `to_base62`. Returns `None` if the input contains any
/// character outside the base62 alphabet (`0-9a-zA-Z`). Empty strings
/// also return `None`.
///
/// Used by `max_djust_id_in` to compute the high-water mark of the
/// id counter from a tree of `VNode`s carrying base62 `djust_id`s,
/// which is the basis of the cross-thread / cross-deserialize id
/// collision fix (#1550 / #1552). Pre-fix, when a `last_vdom`
/// generated by thread A (counter at X) was deserialized into thread
/// B (counter at Y < X) and a new partial render ran via
/// `parse_html_continue`, the freshly-generated ids overlapped with
/// the surviving old-tree ids, and `:scope > [dj-id=N]` resolved to
/// the wrong (new) element on the client.
pub fn from_base62(s: &str) -> Option<u64> {
    if s.is_empty() {
        return None;
    }
    let mut value: u64 = 0;
    for c in s.bytes() {
        let digit: u64 = match c {
            b'0'..=b'9' => (c - b'0') as u64,
            b'a'..=b'z' => (c - b'a' + 10) as u64,
            b'A'..=b'Z' => (c - b'A' + 36) as u64,
            _ => return None,
        };
        value = value.checked_mul(62)?.checked_add(digit)?;
    }
    Some(value)
}

/// Walk a VNode tree and return the maximum decoded `djust_id` value
/// present, or `None` if no node carries a parseable djust_id.
///
/// This is the high-water mark of base62 ids generated in the tree's
/// lifetime. The id counter MUST be advanced past `max + 1` before
/// the next `parse_html_continue` call so that newly-generated ids
/// don't collide with surviving old-tree ids (#1550 / #1552 fix).
pub fn max_djust_id_in(node: &VNode) -> Option<u64> {
    fn walk(node: &VNode, max_so_far: &mut Option<u64>) {
        if let Some(ref id) = node.djust_id {
            if let Some(value) = from_base62(id) {
                *max_so_far = Some(max_so_far.map_or(value, |m| m.max(value)));
            }
        }
        for child in &node.children {
            walk(child, max_so_far);
        }
    }
    let mut max_so_far: Option<u64> = None;
    walk(node, &mut max_so_far);
    max_so_far
}

/// Paths (child-index chains from `root`) of every element whose attribute
/// `key` equals `value`, in document order. ADR-032 D3 step 2: the scoped
/// component patch needs the ONE node carrying `data-component-id`; the
/// caller treats zero or several as "not exact" and takes the full path.
pub fn find_paths_by_attr(root: &VNode, key: &str, value: &str) -> Vec<Vec<usize>> {
    fn walk(
        node: &VNode,
        key: &str,
        value: &str,
        path: &mut Vec<usize>,
        out: &mut Vec<Vec<usize>>,
    ) {
        if node.attrs.get(key).map(String::as_str) == Some(value) {
            out.push(path.clone());
        }
        for (i, child) in node.children.iter().enumerate() {
            path.push(i);
            walk(child, key, value, path, out);
            path.pop();
        }
    }
    let mut out = Vec::new();
    walk(root, key, value, &mut Vec::new(), &mut out);
    out
}

/// Ensure the thread-local id counter is at least `min_value`. If the
/// current counter is already at or above `min_value`, this is a no-op.
/// Otherwise the counter is advanced to `min_value`.
///
/// Wired into `RustLiveViewBackend::render_with_diff` /
/// `render_binary_diff` so that the next `parse_html_continue` call
/// generates ids strictly greater than the maximum id present in
/// `last_vdom`. Defends against thread-pool-handoff and msgpack-
/// roundtrip cases where the counter is reset relative to the
/// existing `last_vdom` ids (#1550 / #1552).
pub fn ensure_id_counter_at_least(min_value: u64) {
    ID_COUNTER.with(|counter| {
        let current = counter.get();
        if current < min_value {
            vdom_trace!(
                "ensure_id_counter_at_least({}): advancing from {}",
                min_value,
                current
            );
            counter.set(min_value);
        }
    });
}

