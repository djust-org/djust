// #1970 — loop parse-cache placeholder splice + dj-id re-walk
// ============================================================================

/// Replace every `<dj-pc h="<hex>">` placeholder element in `tree` (in place)
/// with a clone of the cached parsed subtree roots looked up from `subtrees`
/// (keyed by the decoded hex hash), then re-assign EVERY element dj-id in the
/// whole tree by a pre-order (parent-before-children, document-order) re-walk
/// starting from `counter_base`.
///
/// This is the load-bearing correctness primitive for the #1970 parse cache:
/// dj-ids are purely positional (the parser assigns `next_djust_id()` pre-order
/// — `parser::handle_to_vnode`), so a cached subtree carrying stale ids is
/// position-WRONG when reused elsewhere. Re-walking the ASSEMBLED tree from the
/// same `counter_base` the real parse would have used (`0` for an initial
/// `parse_html`, `max(old_ids)+1` for a continuing `parse_html_continue` after
/// the #1550/#1552 `ensure_id_counter_at_least` bump) reproduces a fresh
/// full-parse's ids byte-for-byte — so the assembled tree, its patches
/// (Insert/Replace embed the new node HTML), and `last_vdom` are all identical
/// to the cache-OFF path.
///
/// Returns `Ok(found_count)` = the number of placeholders replaced, or `Err` if
/// a placeholder's hash had no cached subtree (`subtrees` miss) — the caller
/// treats that as a validation failure and falls back to a full parse. After a
/// successful return, NO `<dj-pc>` element remains in `tree` (the caller asserts
/// this as defense-in-depth against foster-parenting having relocated one).
pub fn splice_loop_placeholders(
    tree: &mut VNode,
    subtrees: &std::collections::HashMap<u64, Vec<VNode>>,
    counter_base: u64,
    sentinel_tag: &str,
) -> std::result::Result<usize, String> {
    let mut found = 0usize;
    splice_children_placeholders(tree, subtrees, sentinel_tag, &mut found)?;
    // Re-assign all dj-ids pre-order from the counter base.
    set_id_counter(counter_base);
    rewalk_djust_ids(tree);
    Ok(found)
}

/// Can a cached item's roots stand in for its `<dj-pc>` placeholder without
/// changing the whitespace a full parse would keep (#2999)?
///
/// The parser keeps a whitespace run only when its nearest neighbour on BOTH
/// sides is inline (text or an inline-level element). An item is parsed alone,
/// so whitespace at its edges is dropped there, and in the reduced page the
/// `dj-pc-*` sentinel is block-level, so whitespace next to it is dropped too.
/// Both agree with the full parse exactly when the item's first and last roots
/// are block-level elements: then every edge whitespace run has a block
/// neighbour in the full parse as well. An inline, text or comment boundary
/// root makes the result depend on the neighbours, so the splice is refused
/// and `render_with_diff` falls back to a full parse.
fn roots_are_whitespace_splice_safe(roots: &[VNode]) -> bool {
    let block_element = |n: &VNode| {
        !n.is_text() && !n.is_comment() && !djust_core::html_whitespace::is_inline_level_tag(&n.tag)
    };
    match (roots.first(), roots.last()) {
        (Some(first), Some(last)) => block_element(first) && block_element(last),
        _ => false,
    }
}

/// Recurse into `node`'s children, replacing `<dj-pc>` placeholder elements with
/// their cached subtree roots. A placeholder can ONLY appear as a child (the
/// loop emits it among sibling items), never as the diff root, so we operate on
/// children vectors. Errors out on a subtree-cache miss.
fn splice_children_placeholders(
    node: &mut VNode,
    subtrees: &std::collections::HashMap<u64, Vec<VNode>>,
    sentinel_tag: &str,
    found: &mut usize,
) -> std::result::Result<(), String> {
    // First, recurse into NON-placeholder children so nested loops (if ever
    // eligible) and deep structure are handled; build a new children vector
    // that expands placeholders in place.
    let old_children = std::mem::take(&mut node.children);
    let mut new_children: Vec<VNode> = Vec::with_capacity(old_children.len());
    for mut child in old_children {
        if child.tag == sentinel_tag {
            let hash = child
                .attrs
                .get("h")
                .and_then(|h| from_base62_hex(h))
                .ok_or_else(|| {
                    format!(
                        "dj-pc placeholder missing/invalid h attr: {:?}",
                        child.attrs.get("h")
                    )
                })?;
            let roots = subtrees
                .get(&hash)
                .ok_or_else(|| format!("no cached parsed subtree for hash {hash:x}"))?;
            if !roots_are_whitespace_splice_safe(roots) {
                return Err(format!(
                    "cached subtree for hash {hash:x} has an inline, text or comment \
                     boundary root; whitespace around it depends on its neighbours (#2999)"
                ));
            }
            for root in roots {
                new_children.push(root.clone());
            }
            *found += 1;
        } else {
            // Recurse: a placeholder could be nested deeper in non-loop
            // structure in principle; handle it uniformly.
            splice_children_placeholders(&mut child, subtrees, sentinel_tag, found)?;
            new_children.push(child);
        }
    }
    node.children = new_children;
    Ok(())
}

/// Pre-order re-walk assigning a fresh `next_djust_id()` to every element node
/// that carries a `djust_id` (text/comment nodes have `djust_id == None` and are
/// skipped — matching the parser, which only ids elements). Keeps the `dj-id`
/// attribute in sync when present.
fn rewalk_djust_ids(node: &mut VNode) {
    if node.djust_id.is_some() {
        let id = next_djust_id();
        // Update the existing `dj-id` attr value IN PLACE via `get_mut` rather
        // than `insert`. `insert` on a key already present can perturb the
        // HashMap's iteration order in some std implementations, which would
        // change the attr order serde emits for a patch's embedded node — making
        // the parse-cache patch JSON differ from the cache-OFF full-parse path
        // (a byte-identity violation observed for `<li dj-id dj-key>`). `get_mut`
        // mutates the value without touching the bucket layout. (#1970)
        if let Some(slot) = node.attrs.get_mut("dj-id") {
            *slot = id.clone();
        }
        node.djust_id = Some(id);
    }
    for child in &mut node.children {
        rewalk_djust_ids(child);
    }
}

/// The placeholder tag PREFIX (kept in sync with
/// `djust_templates::loop_cache::LOOP_PLACEHOLDER_TAG_PREFIX`). The real per-render
/// sentinel tag is `dj-pc-<nonce>` (#1970 security fix); djust_live composes the
/// full tag from the render's nonce and passes it to `splice_loop_placeholders`.
/// Defined here to avoid a djust_vdom → djust_templates dependency (which would
/// invert the layering). Used by [`tree_contains_tag_prefix`] for the
/// residual-placeholder validation guard.
pub const LOOP_PLACEHOLDER_TAG_PREFIX: &str = "dj-pc";

/// Does any element in `tree` have a tag starting with `prefix`? Used by the
/// #1970 splice validation to detect a residual `dj-pc-<nonce>` placeholder
/// (e.g. foster-parenting relocated one out of splice reach) — defense-in-depth.
pub fn tree_contains_tag_prefix(tree: &VNode, prefix: &str) -> bool {
    if tree.tag.starts_with(prefix) {
        return true;
    }
    tree.children
        .iter()
        .any(|c| tree_contains_tag_prefix(c, prefix))
}

/// Decode a lowercase-hex u64 (the placeholder `h` attr). `to_base62` is NOT
/// used for the placeholder hash (it is emitted as `{hash:x}` hex by
/// `render_loop_placeholder`), so decode hex here.
fn from_base62_hex(s: &str) -> Option<u64> {
    u64::from_str_radix(s, 16).ok()
}

/// Serialize a `HashMap<String,String>` of attributes in SORTED key order so
/// the wire format (patch JSON / msgpack) is deterministic regardless of the
/// map's hash-bucket layout. See the `VNode::attrs` field doc (#1970).
fn serialize_attrs_sorted<S>(
    attrs: &HashMap<String, String>,
    serializer: S,
) -> std::result::Result<S::Ok, S::Error>
where
    S: serde::Serializer,
{
    use serde::ser::SerializeMap;
    let mut keys: Vec<&String> = attrs.keys().collect();
    keys.sort();
    let mut map = serializer.serialize_map(Some(keys.len()))?;
    for k in keys {
        map.serialize_entry(k, &attrs[k])?;
    }
    map.end()
}

/// A virtual DOM node
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct VNode {
    pub tag: String,
    /// Element attributes. Serialized in SORTED key order (#1970) so the patch
    /// wire format is DETERMINISTIC: a plain `HashMap` serializes in
    /// hash-bucket order, which differs between two parses of identical content
    /// (RandomState seed + insertion history) — so the parse-cache path
    /// (#1970, which assembles a node via a different parse than the cache-OFF
    /// full parse) could emit a patch whose attr order differed from the
    /// cache-OFF path, a byte-identity violation. Sorting also matches
    /// `to_html`'s already-sorted attribute output. Deserialization is the
    /// default `HashMap` (order-insensitive on read).
    #[serde(serialize_with = "serialize_attrs_sorted")]
    pub attrs: HashMap<String, String>,
    pub children: Vec<VNode>,
    pub text: Option<String>,
    pub key: Option<String>,
    /// Compact unique identifier for reliable patch targeting (e.g., "0", "1a", "2b")
    /// Stored in DOM as data-d attribute for O(1) querySelector lookup
    ///
    /// `default` is REQUIRED alongside `skip_serializing_if` (#1538): under
    /// MessagePack a struct serializes as a positional array, so a `None`
    /// `djust_id` (every text node) drops the trailing element. Without
    /// `default` the sequence-visitor deserializer rejects the short array
    /// with `invalid length 5, expected struct VNode with 6 elements`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub djust_id: Option<String>,
    /// Cached HTML string for to_html() — set on dj-update="ignore" subtrees
    /// to avoid re-serializing unchanged content on every render.
    #[serde(skip)]
    pub cached_html: Option<String>,
}

impl VNode {
    pub fn element(tag: impl Into<String>) -> Self {
        Self {
            tag: tag.into(),
            attrs: HashMap::new(),
            children: Vec::new(),
            text: None,
            key: None,
            djust_id: None,
            cached_html: None,
        }
    }

    pub fn text(content: impl Into<String>) -> Self {
        Self {
            tag: "#text".to_string(),
            attrs: HashMap::new(),
            children: Vec::new(),
            text: Some(content.into()),
            key: None,
            djust_id: None,
            cached_html: None,
        }
    }

    pub fn with_djust_id(mut self, id: impl Into<String>) -> Self {
        self.djust_id = Some(id.into());
        self
    }

    pub fn with_attr(mut self, key: impl Into<String>, value: impl Into<String>) -> Self {
        self.attrs.insert(key.into(), value.into());
        self
    }

    pub fn with_key(mut self, key: impl Into<String>) -> Self {
        self.key = Some(key.into());
        self
    }

    pub fn with_child(mut self, child: VNode) -> Self {
        self.children.push(child);
        self
    }

    pub fn with_children(mut self, children: Vec<VNode>) -> Self {
        self.children = children;
        self
    }

    pub fn is_text(&self) -> bool {
        self.tag == "#text"
    }

    pub fn is_comment(&self) -> bool {
        self.tag == "#comment"
    }

    /// How deeply elements nest in this subtree: this node alone is 1 when it
    /// is an element, 0 for a text or comment node. Iterative, so it is safe
    /// on a tree of any depth.
    ///
    /// The parser keeps every tree it returns within [`MAX_VDOM_DEPTH`]; a
    /// caller that grafts one parsed subtree into another checks the result
    /// with this before it walks the combined tree.
    pub fn element_depth(&self) -> usize {
        let mut deepest = 0;
        let mut stack = vec![(self, 1usize)];
        while let Some((node, depth)) = stack.pop() {
            if node.is_text() || node.is_comment() {
                continue;
            }
            deepest = deepest.max(depth);
            stack.extend(node.children.iter().map(|child| (child, depth + 1)));
        }
        deepest
    }

    /// Serialize the VNode back to HTML string.
    /// This includes dj-id attributes for reliable patch targeting.
    ///
    /// `self` is serialized as if parsed in an HTML context (the `<body>`
    /// the VDOM root sits in); an `svg` or `math` element below it switches
    /// to foreign content (see [`Namespace`]). For a root whose namespace
    /// the parser reported, use [`VNode::to_html_in`].
    pub fn to_html(&self) -> String {
        self.to_html_in(Some(ChildContext::Html.child_namespace(self)))
    }

    /// [`VNode::to_html`] for an element `self` whose namespace is `ns`, as
    /// [`parse_html_with_namespace`] reports it for the root: under a root
    /// inside `<svg>` (`<svg><g dj-root>`), a `<style>` is SVG and its text
    /// is escaped. `None` means the namespace is not known; then the text
    /// of every raw-text element is escaped, which can only over-escape.
    pub fn to_html_in(&self, ns: Option<Namespace>) -> String {
        let mut html = String::new();
        let place = Place {
            read_as: ns,
            actual: ns,
            verbatim: false,
            scripting: true,
        };
        self.write_html(&mut html, place);
        html
    }

    /// Serialize an `InsertSubtree` payload node. The client parses the
    /// payload as children of the node's real parent, in that parent's
    /// namespace (an SVG or MathML parent gets an `<svg>` / `<math>`
    /// wrapper), with `<template>.innerHTML`, so with scripting disabled.
    /// `parent` is how the real parent places its children, or `None` when
    /// that is not known (the text of every raw-text element is then
    /// escaped).
    pub(crate) fn to_html_for_client(&self, parent: Option<ChildContext>) -> String {
        let mut html = String::new();
        let ns = parent.map(|context| context.child_namespace(self));
        let place = Place {
            read_as: ns,
            actual: ns,
            verbatim: false,
            scripting: false,
        };
        self.write_html(&mut html, place);
        html
    }

    /// Serialize for an HTML parser with scripting disabled that reads the
    /// output in an HTML context (`<template>.innerHTML` with no wrapper).
    /// `parent` is how the node's real parent places its children, or
    /// `None` when that is not known.
    #[cfg(test)]
    pub(crate) fn to_html_read_as_html(&self, parent: Option<ChildContext>) -> String {
        let mut html = String::new();
        let place = Place {
            read_as: Some(ChildContext::Html.child_namespace(self)),
            actual: parent.map(|context| context.child_namespace(self)),
            verbatim: false,
            scripting: false,
        };
        self.write_html(&mut html, place);
        html
    }

    #[cfg(test)]
    pub(crate) fn to_html_out_of_context(&self) -> String {
        self.to_html_read_as_html(None)
    }

    /// Append directly to the render's buffer; descendants do not allocate
    /// intermediate HTML strings. Cached ignored subtrees remain verbatim.
    ///
    /// `place` is where this node sits when it is an element (see [`Place`]).
    /// A text node takes its parent's decision: `place.verbatim` is true
    /// when the parent writes its text raw.
    fn write_html(&self, html: &mut String, place: Place) {
        if let Some(ref cached) = self.cached_html {
            // The cache was written in the node's real context, for the
            // page's parser. Reuse it only where the output is read in that
            // same context. An `InsertSubtree` payload is, but parsed with
            // scripting disabled, which reads a `<noscript>` differently.
            if place.read_as.is_some()
                && place.read_as == place.actual
                && (place.scripting || !contains_noscript_tag(cached))
            {
                html.push_str(cached);
                return;
            }
        }

        if self.is_text() {
            let text = self.text.as_deref().unwrap_or_default();
            // Raw text elements (<script>, <style>) must not have their
            // text content HTML-escaped — the browser treats the bytes
            // literally, so escaping `&` to `&amp;` would corrupt JS/CSS
            // code and cause double-escaping bugs (#613).
            if place.verbatim {
                html.push_str(text);
            } else {
                write_escaped(html, text, false);
            }
            return;
        }

        if self.is_comment() {
            // Comment nodes: render as HTML comments
            html.push_str("<!--");
            html.push_str(self.text.as_deref().unwrap_or_default());
            html.push_str("-->");
            return;
        }

        // Void elements that don't have closing tags
        let void_elements = [
            "area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param",
            "source", "track", "wbr",
        ];
        let is_void = void_elements.contains(&self.tag.as_str());

        let content = place.content_of(self);
        let verbatim = content == Content::Verbatim;

        // Opening tag
        html.push('<');
        html.push_str(&self.tag);

        // Sorting is needed only for multiple attributes. Most hydrated
        // elements carry just their generated id.
        if self.attrs.len() <= 1 {
            for (key, value) in &self.attrs {
                write_attribute(html, key, value);
            }
        } else {
            let mut attrs: Vec<_> = self.attrs.iter().collect();
            attrs.sort_unstable_by_key(|(key, _)| *key);
            for (key, value) in attrs {
                write_attribute(html, key, value);
            }
        }

        if is_void {
            html.push_str(" />");
        } else {
            html.push('>');

            // Children — propagate raw-text context so text nodes inside
            // <script>/<style> are emitted verbatim, and the namespace each
            // child element has.
            let read_as = place.read_as.map(|ns| ns.children_of(self));
            let actual = place.actual.map(|ns| ns.children_of(self));
            let write_children = |html: &mut String| {
                for child in &self.children {
                    let child_place = Place {
                        read_as: read_as.map(|c| c.child_namespace(child)),
                        actual: actual.map(|c| c.child_namespace(child)),
                        verbatim,
                        scripting: place.scripting,
                    };
                    child.write_html(html, child_place);
                }
            };
            if content == Content::EscapedMarkup {
                // Read as raw text, the children's markup would be text, and
                // a descendant's own end tag (`<style><style>a</style>`)
                // would end this element: write all of it as escaped text.
                let mut inner = String::new();
                write_children(&mut inner);
                write_escaped(html, &inner, false);
            } else {
                write_children(html);
            }

            // Closing tag
            html.push_str("</");
            html.push_str(&self.tag);
            html.push('>');
        }
    }
}

/// Splice old VDOM subtrees into a new VDOM for `dj-update="ignore"` nodes.
///
/// After parsing a new render, this function walks both old and new VDOM trees
/// in parallel. When it finds a node with `dj-update="ignore"` in the new tree,
/// it replaces the new node's children with the old node's children (preserving
/// IDs and cached HTML). This means:
/// - The diff step sees identical subtrees → zero patches for ignored sections
/// - `to_html()` uses `cached_html` → skip serialization for ignored sections
pub fn splice_ignore_subtrees(old: &VNode, new: &mut VNode) {
    if old.tag != new.tag {
        return;
    }
    if new.attrs.get("dj-update").map(|v| v.as_str()) == Some("ignore") {
        // Replace the new subtree's children with old's (preserving IDs).
        // NOTE (#1252): Do NOT copy `old.cached_html` — that cache may be
        // stale relative to the spliced children if the surrounding markup
        // changed (e.g., a wrapping conditional toggled). Clear the cache
        // so `cache_ignore_subtree_html` (called after splice on the
        // server's render path) recomputes from current children.
        new.children = old.children.clone();
        new.djust_id = old.djust_id.clone();
        new.cached_html = None;
        return;
    }
    // Recurse into children by position
    let len = old.children.len().min(new.children.len());
    for i in 0..len {
        splice_ignore_subtrees(&old.children[i], &mut new.children[i]);
    }
}

/// Cache the HTML serialization for all `dj-update="ignore"` subtrees in a VDOM tree.
/// Call this after the first render so subsequent `to_html()` calls can skip
/// serialization for these static sections.
///
/// `node` is taken to sit in HTML content (see [`VNode::to_html`]); for a
/// node whose namespace is known, use [`cache_ignore_subtree_html_in`].
pub fn cache_ignore_subtree_html(node: &mut VNode) {
    let ns = ChildContext::Html.child_namespace(node);
    cache_ignore_subtree_html_in(node, ns);
}

/// [`cache_ignore_subtree_html`] for a `node` in namespace `ns`: the cached
/// HTML is what [`VNode::to_html_in`] writes for the node at this position,
/// so a `<style>` in an ignored `<svg>` subtree is still escaped.
pub fn cache_ignore_subtree_html_in(node: &mut VNode, ns: Namespace) {
    if node.attrs.get("dj-update").map(|v| v.as_str()) == Some("ignore") {
        if node.cached_html.is_none() {
            let mut html = String::new();
            node.write_html(&mut html, Place::in_context(ns));
            node.cached_html = Some(html);
        }
        return; // Don't recurse — entire subtree is cached
    }
    let children_ns = ns.children_of(node);
    for child in &mut node.children {
        let child_ns = children_ns.child_namespace(child);
        cache_ignore_subtree_html_in(child, child_ns);
    }
}

/// Where a node sits, as the serializer sees it.
///
/// Raw-text elements (`djust_core::raw_text`: `script`, `style`, `noscript`,
/// `xmp`, `iframe`, `noembed`, `noframes`, `plaintext`) are written exactly
/// as the HTML serialization algorithm writes them: in the HTML namespace
/// their text goes out verbatim, as the parser kept it (escaping it again
/// turned `&amp;` into `&amp;amp;`, #613 / #3045); anywhere else their text
/// is escaped like any other, because a foreign `<svg><style>` holds text
/// the parser DECODED.
///
/// Verbatim is exact only when the element really is an HTML raw-text
/// element: then the text came from the tokenizer, which already ended the
/// element wherever it could end, so the bytes read back the same. That
/// includes a script whose text holds `</script>` inside the script-data
/// escape states (`<!-- document.write("<script></script>") -->`) and a
/// `<plaintext>` holding `</plaintext>`.
///
/// An `InsertSubtree` payload is read in the node's real context: the client
/// parses it in the namespace of the parent it is inserted into
/// ([`VNode::to_html_for_client`]), so it is written exactly like the page,
/// except that the client's parse has scripting disabled and so reads a
/// `noscript`'s content as markup: that is written as markup, its text
/// escaped.
///
/// When the output is read in a context the node does not really have (an
/// HTML parse of nodes that are really SVG or MathML: `read_as == Html`,
/// `actual != Html`), the two differ: a `<style>` is read as HTML raw text
/// although its text was decoded as SVG. There the text is written verbatim
/// only when the element holds nothing but text and the tokenizer would keep
/// all of it inside the element ([`raw_text_stays_inside`]); otherwise it is escaped. An element
/// child counts too: the parser reads its markup as raw text, and a
/// descendant with the same name (`<style><style>a</style>…</style>`,
/// also deeper down) writes the end tag that closes the element, after
/// which the rest is read as markup. Such an element's whole content (the
/// children's serialization) is written as escaped text, so nothing in it
/// can end the element early. The same holds for the RCDATA names `title`
/// and `textarea` (an SVG `<title>` holding HTML is read as an HTML
/// `<title>`); their text alone is escaped as usual. A `noscript` read
/// there is always escaped: the client parses with scripting disabled, so
/// it reads the element's content as markup.
#[derive(Clone, Copy, Debug)]
struct Place {
    /// The namespace the parser that reads the output gives this element.
    /// `None` when that is not known: raw-text names are then escaped.
    read_as: Option<Namespace>,
    /// The namespace the element really has in the page, or `None` when the
    /// output is serialized away from that context.
    actual: Option<Namespace>,
    /// For a text node: does its parent write its text verbatim?
    verbatim: bool,
    /// Does the parser that reads the output have scripting enabled? The
    /// page's parser does; the client's `<template>.innerHTML` parse of an
    /// `InsertSubtree` payload does not, and there a `noscript` holds
    /// markup, not raw text.
    scripting: bool,
}

impl Place {
    /// An element serialized in its real context, in namespace `ns`.
    fn in_context(ns: Namespace) -> Self {
        Place {
            read_as: Some(ns),
            actual: Some(ns),
            verbatim: false,
            scripting: true,
        }
    }

    /// How `element`, placed here, writes its content.
    fn content_of(self, element: &VNode) -> Content {
        let raw_text = djust_core::raw_text::is_raw_text_element(&element.tag);
        // `title` and `textarea` (RCDATA): the tokenizer reads their content
        // as text too, but decodes references, so escaped text is exact.
        let rcdata = ["title", "textarea"]
            .iter()
            .any(|tag| element.tag.eq_ignore_ascii_case(tag));
        if self.read_as != Some(Namespace::Html) || !(raw_text || rcdata) {
            return Content::Markup;
        }
        // `noscript` is raw text only to a parser with scripting enabled.
        // The client parses a payload with `<template>.innerHTML`, which has
        // scripting disabled, so there its content is read as markup:
        // escaped text reads back as the same text. The same holds for a
        // `noscript` that is not really HTML (`<svg><noscript>`).
        if element.tag.eq_ignore_ascii_case("noscript")
            && (!self.scripting || self.actual != Some(Namespace::Html))
        {
            return Content::Markup;
        }
        if self.actual == Some(Namespace::Html) {
            return if raw_text {
                Content::Verbatim
            } else {
                Content::Markup
            };
        }
        // Read as HTML raw text, but the content is not known to be HTML
        // raw text. Any child that is not text (an element, a comment) is
        // read back as text, so the end tag of a same-named descendant
        // (or, in an SVG `<title>`, a script's `</title>`) would end this
        // element: escape the whole content.
        if element.children.iter().any(|child| !child.is_text()) {
            return Content::EscapedMarkup;
        }
        if rcdata {
            return Content::Markup;
        }
        // Text only: verbatim when the tokenizer would keep all of it
        // inside the element.
        let mut text = String::new();
        for child in &element.children {
            text.push_str(child.text.as_deref().unwrap_or_default());
        }
        if raw_text_stays_inside(&element.tag, &text) {
            Content::Verbatim
        } else {
            Content::Markup
        }
    }
}

/// How an element writes its content: [`Place::content_of`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Content {
    /// Children as usual: elements as markup, text escaped.
    Markup,
    /// Text children as they are (HTML raw text).
    Verbatim,
    /// The children's whole serialization, escaped as one text: a raw-text
    /// element read out of context that holds more than text.
    EscapedMarkup,
}

/// The namespace the HTML parser puts an element in, as the serializer needs
/// it: raw-text handling applies only to HTML-namespace elements (#3045
/// list), so `<svg><style>` text is escaped and `<style>` text is not.
///
/// A VNode keeps no namespace (the parser stores the local name), so the
/// serializer recomputes it top-down with the tree-construction rules
/// html5ever applies: `svg` / `math` start foreign content; inside SVG,
/// `foreignObject`, `desc` and `title` hold HTML again (HTML integration
/// points), as does a MathML `annotation-xml` whose `encoding` is
/// `text/html` or `application/xhtml+xml`; a MathML `mi`, `mo`, `mn`, `ms`
/// or `mtext` holds HTML except `mglyph` / `malignmark` (text integration
/// points); `svg` inside `annotation-xml` is SVG.
///
/// One case the top-down rule gets wrong: an element foster-parented out of
/// a `<table>` inside a MathML text integration point
/// (`<math><mi><malignmark><table><malignmark>`) is HTML in the parsed tree
/// but computed as MathML here, so its raw text is escaped. That only
/// over-escapes; recording each element's namespace at parse time would need
/// a VNode layout change.
///
/// The root's own namespace cannot be recomputed from the tree at all: a
/// `dj-root` on `<g>` inside `<svg>` is an SVG element although nothing in
/// the VDOM says so. The parser reports it ([`parse_html_with_namespace`]),
/// and the namespace-aware entry points ([`VNode::to_html_in`],
/// [`cache_ignore_subtree_html_in`], [`diff_in`]) take it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Namespace {
    Html,
    Svg,
    MathMl,
}

/// How a parent places its child elements: [`ChildContext::child_namespace`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum ChildContext {
    /// HTML content: `svg` and `math` switch, anything else is HTML.
    Html,
    /// Every child shares the parent's foreign namespace.
    Foreign(Namespace),
    /// A MathML text integration point.
    MathText,
    /// A MathML `annotation-xml` that is not an HTML integration point.
    AnnotationXml,
}

impl Namespace {
    /// How an element in this namespace places its children.
    pub(crate) fn children_of(self, element: &VNode) -> ChildContext {
        let tag = element.tag.as_str();
        match self {
            Namespace::Html => ChildContext::Html,
            Namespace::Svg => {
                if ["foreignObject", "desc", "title"]
                    .iter()
                    .any(|t| tag.eq_ignore_ascii_case(t))
                {
                    ChildContext::Html
                } else {
                    ChildContext::Foreign(Namespace::Svg)
                }
            }
            Namespace::MathMl => {
                if ["mi", "mo", "mn", "ms", "mtext"]
                    .iter()
                    .any(|t| tag.eq_ignore_ascii_case(t))
                {
                    ChildContext::MathText
                } else if tag.eq_ignore_ascii_case("annotation-xml") {
                    let html_encoding = element.attrs.get("encoding").is_some_and(|e| {
                        e.eq_ignore_ascii_case("text/html")
                            || e.eq_ignore_ascii_case("application/xhtml+xml")
                    });
                    if html_encoding {
                        ChildContext::Html
                    } else {
                        ChildContext::AnnotationXml
                    }
                } else {
                    ChildContext::Foreign(Namespace::MathMl)
                }
            }
        }
    }
}

impl ChildContext {
    /// The namespace of `child` placed in this context. Only meaningful for
    /// an element; text and comments pass it through unused.
    pub(crate) fn child_namespace(self, child: &VNode) -> Namespace {
        let tag = child.tag.as_str();
        let html_rules = || {
            if tag.eq_ignore_ascii_case("svg") {
                Namespace::Svg
            } else if tag.eq_ignore_ascii_case("math") {
                Namespace::MathMl
            } else {
                Namespace::Html
            }
        };
        match self {
            ChildContext::Html => html_rules(),
            ChildContext::Foreign(ns) => ns,
            ChildContext::MathText => {
                if tag.eq_ignore_ascii_case("mglyph") || tag.eq_ignore_ascii_case("malignmark") {
                    Namespace::MathMl
                } else {
                    html_rules()
                }
            }
            ChildContext::AnnotationXml => {
                if tag.eq_ignore_ascii_case("svg") {
                    Namespace::Svg
                } else {
                    Namespace::MathMl
                }
            }
        }
    }
}

/// The namespace of the element at `path` below `root`, an element in
/// namespace `root_ns`; `None` when `path` does not lead to an element.
pub fn namespace_at_path(root: &VNode, root_ns: Namespace, path: &[usize]) -> Option<Namespace> {
    let mut node = root;
    let mut ns = root_ns;
    for &index in path {
        let child = node.children.get(index)?;
        ns = ns.children_of(node).child_namespace(child);
        node = child;
    }
    (!node.is_text() && !node.is_comment()).then_some(ns)
}

/// Does `html` hold a `noscript` tag (any ASCII case)?
fn contains_noscript_tag(html: &str) -> bool {
    html.as_bytes()
        .windows(9)
        .any(|w| w[0] == b'<' && w[1..].eq_ignore_ascii_case(b"noscript"))
}

fn html_escape(text: &str) -> String {
    let mut html = String::with_capacity(text.len());
    write_escaped(&mut html, text, false);
    html
}

fn write_attribute(html: &mut String, key: &str, value: &str) {
    html.push(' ');
    html.push_str(key);
    html.push_str("=\"");
    write_escaped(html, value, true);
    html.push('"');
}

/// Does `text` hold an end tag for `tag` as the HTML tokenizer reads one in
/// raw text: `</`, the name in any ASCII case, then whitespace, `/` or `>`?
fn contains_end_tag(text: &str, tag: &str) -> bool {
    let bytes = text.as_bytes();
    let name = tag.as_bytes();
    let mut from = 0;
    while let Some(found) = text[from..].find("</") {
        let start = from + found + 2;
        let end = start + name.len();
        if end < bytes.len()
            && bytes[start..end].eq_ignore_ascii_case(name)
            && matches!(
                bytes[end],
                b'\t' | b'\n' | b'\x0c' | b'\r' | b' ' | b'/' | b'>'
            )
        {
            return true;
        }
        from = from + found + 2;
    }
    false
}

/// Would `text`, read by an HTML parser as the body of an HTML raw-text
/// element `tag`, stay inside that element, so that the `</tag>` written
/// after it closes the element? This follows the tokenizer: in RAWTEXT
/// (`style`, `xmp`, `iframe`, `noembed`, `noframes`, `noscript`) only an
/// end tag for the element ends it; `script` is read with the script-data
/// states, where `<!--` … `<script>` (double-escaped) hides `</script>` and
/// also stops the next `</script>` from closing; nothing ends `plaintext`.
fn raw_text_stays_inside(tag: &str, text: &str) -> bool {
    if tag.eq_ignore_ascii_case("plaintext") {
        true
    } else if tag.eq_ignore_ascii_case("script") {
        script_data_stays_inside(text.as_bytes())
    } else {
        !contains_end_tag(text, tag)
    }
}

/// [`raw_text_stays_inside`] for `script`: the tokenizer's script-data,
/// escaped and double-escaped states.
fn script_data_stays_inside(text: &[u8]) -> bool {
    #[derive(Clone, Copy, PartialEq, Eq)]
    enum State {
        Data,
        Escaped,
        EscapedDash,
        EscapedDashDash,
        Double,
        DoubleDash,
        DoubleDashDash,
    }
    let delimiter = |at: usize| {
        text.get(at)
            .is_some_and(|&c| matches!(c, b'\t' | b'\n' | b'\x0c' | b'\r' | b' ' | b'/' | b'>'))
    };
    // `script` at `at`, then a delimiter: a name the states compare.
    let script_at = |at: usize| {
        text.get(at..at + 6)
            .is_some_and(|name| name.eq_ignore_ascii_case(b"script"))
            && delimiter(at + 6)
    };
    let mut state = State::Data;
    let mut i = 0;
    while i < text.len() {
        let c = text[i];
        match state {
            State::Data => {
                if c == b'<' {
                    if text.get(i + 1) == Some(&b'/') && script_at(i + 2) {
                        return false; // an end tag: the element ends here
                    }
                    if text[i + 1..].starts_with(b"!--") {
                        state = State::EscapedDashDash;
                        i += 4;
                        continue;
                    }
                }
            }
            State::Escaped | State::EscapedDash | State::EscapedDashDash => match c {
                b'<' => {
                    if text.get(i + 1) == Some(&b'/') && script_at(i + 2) {
                        return false;
                    }
                    if script_at(i + 1) {
                        state = State::Double;
                        i += 7;
                        continue;
                    }
                    state = State::Escaped;
                }
                b'-' => {
                    state = if state == State::Escaped {
                        State::EscapedDash
                    } else {
                        State::EscapedDashDash
                    };
                }
                b'>' if state == State::EscapedDashDash => state = State::Data,
                _ => state = State::Escaped,
            },
            State::Double | State::DoubleDash | State::DoubleDashDash => match c {
                b'<' => {
                    if text.get(i + 1) == Some(&b'/') && script_at(i + 2) {
                        state = State::Escaped;
                        i += 8;
                        continue;
                    }
                    state = State::Double;
                }
                b'-' => {
                    state = if state == State::Double {
                        State::DoubleDash
                    } else {
                        State::DoubleDashDash
                    };
                }
                b'>' if state == State::DoubleDashDash => state = State::Data,
                _ => state = State::Double,
            },
        }
        i += 1;
    }
    // In a double-escaped state the `</script>` written next only leaves
    // that state; it would not close the element.
    !matches!(
        state,
        State::Double | State::DoubleDash | State::DoubleDashDash
    )
}

/// Escape in one pass while copying unchanged spans directly. Text and
/// attribute escaping deliberately differ for quotes and non-breaking spaces.
fn write_escaped(html: &mut String, text: &str, attribute: bool) {
    let mut start = 0;
    for (index, ch) in text.char_indices() {
        let escaped = match ch {
            '&' => "&amp;",
            '<' => "&lt;",
            '>' => "&gt;",
            '"' if attribute => "&quot;",
            '\u{00a0}' if !attribute => "&nbsp;",
            _ => continue,
        };
        html.push_str(&text[start..index]);
        html.push_str(escaped);
        start = index + ch.len_utf8();
    }
    html.push_str(&text[start..]);
}

/// A patch operation to apply to the DOM
///
/// Each patch includes:
/// - `path`: Index-based path for fallback traversal
/// - `d`: Compact djust_id for O(1) querySelector lookup (e.g., "1a")
///
/// Client resolution strategy:
/// 1. Try querySelector('[data-d="1a"]') - fast, reliable
/// 2. Fall back to index-based path traversal if ID not found
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum Patch {
    /// Replace a node at path
    Replace {
        path: Vec<usize>,
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        node: VNode,
    },
    /// Update text content
    SetText {
        path: Vec<usize>,
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        text: String,
    },
    /// Set an attribute
    SetAttr {
        path: Vec<usize>,
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        key: String,
        value: String,
    },
    /// Remove an attribute
    RemoveAttr {
        path: Vec<usize>,
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        key: String,
    },
    /// Insert a child at index (d = parent's djust_id)
    InsertChild {
        path: Vec<usize>,
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        index: usize,
        node: VNode,
        /// The djust_id of the sibling currently at `index` (the reference node).
        /// The client can use this for ID-based insertBefore instead of index-based,
        /// preventing mis-targeting when earlier patches shift sibling positions.
        #[serde(skip_serializing_if = "Option::is_none")]
        ref_d: Option<String>,
    },
    /// Remove a child at index (d = parent's djust_id)
    RemoveChild {
        path: Vec<usize>,
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        index: usize,
        /// The child's djust_id for ID-based resolution on the client.
        /// Prevents stale-index mis-targeting when earlier patches shift sibling positions.
        #[serde(skip_serializing_if = "Option::is_none")]
        child_d: Option<String>,
    },
    /// Move a child from one index to another (d = parent's djust_id)
    MoveChild {
        path: Vec<usize>,
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        from: usize,
        to: usize,
        /// The child's djust_id for ID-based resolution on the client.
        /// Prevents stale-index mis-targeting when multiple MoveChild patches
        /// shift DOM positions before subsequent patches are applied.
        #[serde(skip_serializing_if = "Option::is_none")]
        child_d: Option<String>,
    },
    // --- [dj-virtual] keyed splice ops (ADR-026, #2017 items 2-4) ---
    //
    // A [dj-virtual] container's children are only the visible WINDOW on the
    // client; the full collection lives in the list's item pool with
    // off-window rows detached. INDEX-addressed ops (InsertChild/MoveChild/
    // RemoveChild above) are therefore meaningless for such a parent: index 7
    // means "the 8th item" to the differ and "the 8th VISIBLE item" to the DOM.
    //
    // These variants address items by KEY instead, so the client can apply
    // them to the pool without the DOM being the source of truth. Emitted only
    // when the parent carries `dj-virtual` AND the feature flag is on
    // (`diff::set_virtual_keyed_ops`). Default ON since 1.1.1 via Python's
    // LIVEVIEW_CONFIG; the Rust static itself stays false so an unwired
    // embedding fails safe — see the note on VIRTUAL_KEYED_OPS in diff.rs.
    //
    // Wire note (corrected — the first version of this comment was wrong, and
    // so is the older one on `MoveSubtree` below). `#[serde(tag = "type")]`
    // does NOT force a map encoding under msgpack: `rmp_serde` encodes an
    // internally-tagged enum as a POSITIONAL array with the tag in slot 0.
    // Measured: `SetText { d: None }` -> first byte 0x93 (FIXARRAY), and it
    // fails its own round-trip with "invalid length 2, expected struct variant
    // Patch::SetText with 3 elements"
    // because `skip_serializing_if` dropped the interior `d` — the exact
    // #1541 shape. That breakage is PRE-EXISTING and affects every variant,
    // not just these; `render_binary_diff` (djust_live/src/lib.rs, the only
    // only msgpack producer and has no non-test consumer today, which is why
    // it has gone unnoticed. Tracked separately rather than widened into this
    // change (#1079); pinned as-is in `wire_protocol_snapshot.rs` so the
    // reality is recorded rather than assumed.
    //
    // These variants therefore keep `skip_serializing_if` to match every
    // sibling variant: the LIVE path is `serde_json` (a named map), where it
    // is genuinely safe and saves wire bytes on every patch.
    /// Update a keyed item's CONTENT in a `[dj-virtual]` parent's pool.
    ///
    /// The inner `patches` are addressed RELATIVE to the item's own root, so
    /// the client resolves the row by key and applies them with that node as
    /// the root. That is what makes an off-window update land: the row is
    /// detached, held only in `state.items`, and mutating a detached node is
    /// fine — the change appears when it scrolls back into the window.
    ///
    /// Without this, survivors' content was emitted as ordinary path-addressed
    /// patches whose path was the item's ABSOLUTE index. For a windowed
    /// container that index is meaningless, and the patches carry no dj-id
    /// (text nodes have none), so they resolved positionally: measured,
    /// editing row 0 after a scroll silently rewrote row 7 (#2136).
    VirtualUpdate {
        path: Vec<usize>,
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        /// The item's key (from `dj-key`), NOT an index.
        key: String,
        /// Patches relative to the item's own root (`path: []` IS the row).
        patches: Vec<Patch>,
    },
    /// Insert a keyed item into a `[dj-virtual]` parent's pool.
    VirtualInsert {
        path: Vec<usize>,
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        /// The item's key (from `dj-key`), NOT an index.
        key: String,
        node: VNode,
        /// Insert before the item with this key; `None` appends at the tail.
        #[serde(skip_serializing_if = "Option::is_none")]
        before_key: Option<String>,
    },
    /// Move an existing keyed item within a `[dj-virtual]` parent's pool.
    VirtualMove {
        path: Vec<usize>,
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        key: String,
        /// Move before the item with this key; `None` moves to the tail.
        #[serde(skip_serializing_if = "Option::is_none")]
        before_key: Option<String>,
    },
    /// Remove a keyed item from a `[dj-virtual]` parent's pool.
    VirtualRemove {
        path: Vec<usize>,
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        key: String,
    },
    /// Remove a `dj-if` keyed subtree by marker id.
    ///
    /// Capability of issue #1358 (keyed VDOM diff for `{% if %}` conditional
    /// subtrees, re-open of #256 Option A). Iter 3 of v0.9.4-1.
    ///
    /// The client locates the `<!--dj-if id="X"-->...<!--/dj-if-->` marker
    /// pair by id and removes the bracketed range. Position-based path
    /// tracking is bypassed — the boundary's id normalizes positions, so
    /// sibling shifts no longer cascade into patch failures.
    RemoveSubtree {
        /// Boundary marker id (e.g. `"if-a3b1c2d4-0"`).
        id: String,
    },
    /// Insert a `dj-if` keyed subtree at a parent + index.
    ///
    /// Capability of issue #1358. The `html` carries the full marker pair
    /// (open `<!--dj-if id="..."-->`, body, close `<!--/dj-if-->`) — Shape A
    /// per Iter 2's locked wire contract. The client parses it via an inert
    /// `<template>.innerHTML` so any nested `<script>` tags are NOT executed.
    InsertSubtree {
        /// Boundary marker id (e.g. `"if-a3b1c2d4-1"`).
        id: String,
        /// Parent path (same shape as `InsertChild.path`).
        path: Vec<usize>,
        /// Parent's djust_id (same role as `InsertChild.d`).
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        /// Index within the parent's significant-children where the open
        /// marker should land (same semantics as `InsertChild.index`).
        index: usize,
        /// Full HTML fragment: `<!--dj-if id="..."-->{body}<!--/dj-if-->`.
        html: String,
    },
    /// Reposition an existing (matched) `dj-if` keyed subtree (#1666).
    ///
    /// When a `{% if %}` boundary is present in both old and new but its
    /// position among the parent's significant children shifted (siblings were
    /// added/removed/reordered around it), the marker span must move. The
    /// markers are `#comment` nodes with no `djust_id`, so a plain `MoveChild`
    /// can't target them — this is the "move" verb for boundary spans,
    /// completing the Remove/Insert/Move trio.
    ///
    /// The client locates the `<!--dj-if id="X"-->...<!--/dj-if-->` marker pair
    /// by `id`, detaches the whole range, and re-inserts it at `index` within
    /// the parent (resolved by `d`, path fallback). Unlike Remove+Insert this
    /// preserves the inner nodes' identity (and any state/focus tied to inner
    /// dj-ids). `index` is the open marker's position among the parent's
    /// significant children (same frame as `InsertSubtree.index`).
    ///
    /// NOTE: this paragraph used to claim that `#[serde(tag = "type")]` makes
    /// `Patch` map-encoded even under msgpack, and it is FALSE — `rmp_serde`
    /// encodes an internally-tagged enum as a positional array (measured:
    /// `SetText` -> 0x93 FIXARRAY, round-trip fails). The `skip_serializing_if`
    /// on `d` is wire-safe on the LIVE path because that path is `serde_json`,
    /// not because of the tag. See the corrected note on `VirtualInsert`.
    MoveSubtree {
        /// Boundary marker id (e.g. `"if-a3b1c2d4-0"`).
        id: String,
        /// Parent path (same shape as `InsertSubtree.path`).
        path: Vec<usize>,
        /// Parent's djust_id (same role as `InsertSubtree.d`).
        #[serde(skip_serializing_if = "Option::is_none")]
        d: Option<String>,
        /// Target index of the open marker among the parent's significant
        /// children (same frame as `InsertSubtree.index`).
        index: usize,
    },
}

/// Compute the difference between two virtual DOM trees
pub fn diff(old: &VNode, new: &VNode) -> Vec<Patch> {
    vdom_trace!("===== DIFF START =====");
    vdom_trace!(
        "old_root: <{}> id={:?} children={}",
        old.tag,
        old.djust_id,
        old.children.len()
    );
    vdom_trace!(
        "new_root: <{}> id={:?} children={}",
        new.tag,
        new.djust_id,
        new.children.len()
    );

    let patches = diff::diff_nodes_in(old, new, &[], Some(ChildContext::Html.child_namespace(new)));

    vdom_trace!(
        "===== DIFF COMPLETE: {} patches generated =====",
        patches.len()
    );
    if should_trace() {
        for (i, patch) in patches.iter().enumerate() {
            eprintln!("[VDOM TRACE] Patch[{}]: {:?}", i, patch);
        }
    }

    patches
}

